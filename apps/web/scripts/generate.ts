// Writes the files the preview needs to render the registry's raw source:
//
// - `__generated__/styles.css`: every style's rules as `.style-{name} .cn-*`,
//   with the default style filled in for markers a style doesn't define, so
//   the preview matches what the build publishes.
// - `__generated__/icons.ts`: the lucide icons `IconPlaceholder` names, so
//   the preview doesn't bundle all of `lucide-react`.
// - `__generated__/registries.ts`: each base's `registry.json` and the demos
//   in its `examples/`, so adding or removing a base or a demo needs no
//   imports by hand.
//
//   node scripts/generate.ts [--watch]

import { promises as fs, watch } from "node:fs";
import path from "node:path";

import { BASES, STYLES } from "../src/registry/config.ts";
import {
  GENERATED_PATH,
  getMarkers,
  getStyleMaps,
  REGISTRY_PATH,
  writeFileIfChanged,
} from "./registry.ts";

const HEADER =
  "This file is generated by scripts/generate.ts. Do not edit it directly.";

async function readSources(
  dir = path.join(REGISTRY_PATH, "bases"),
): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const sources = await Promise.all(
    entries.map(async (entry) => {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) return readSources(file);
      return /\.tsx?$/.test(entry.name)
        ? [await fs.readFile(file, "utf8")]
        : [];
    }),
  );
  return sources.flat();
}

function toPascalCase(name: string) {
  return name.replace(/(?:^|-)(\w)/g, (_, char: string) => char.toUpperCase());
}

// `examples/{item}-demo.tsx` is the demo for `{item}`.
async function getRegistriesModule() {
  const imports: string[] = [];
  const registries: string[] = [];
  const examples: string[] = [];

  for (const { name: base } of BASES) {
    const registry = `${toPascalCase(base)}Registry`;
    imports.push(
      `import ${registry} from "@/registry/bases/${base}/registry.json";`,
    );
    registries.push(`  ${base}: ${registry},`);

    const demos = (
      await fs
        .readdir(path.join(REGISTRY_PATH, "bases", base, "examples"))
        .catch((error: NodeJS.ErrnoException) => {
          // A base without demos has no `examples/` folder.
          if (error.code === "ENOENT") return [];
          throw error;
        })
    )
      .filter((file) => file.endsWith("-demo.tsx"))
      .sort();
    const entries = demos.map((file) => {
      const item = file.replace(/-demo\.tsx$/, "");
      const demo = `${toPascalCase(base)}${toPascalCase(item)}Demo`;
      imports.push(
        `import ${demo} from "@/registry/bases/${base}/examples/${item}-demo";`,
      );
      return `    "${item}": ${demo},`;
    });
    examples.push(`  ${base}: {\n${entries.join("\n")}\n  },`);
  }

  return `// ${HEADER}

import type * as React from "react";
import type { Registry } from "shadcn/schema";

import type { BaseName } from "@/registry/config";

${imports.join("\n")}

export const REGISTRIES = {
${registries.join("\n")}
} as Record<BaseName, Registry>;

// Demos shown in the preview, by base and item name.
export const EXAMPLES: Record<
  BaseName,
  Record<string, React.ComponentType>
> = {
${examples.join("\n")}
};
`;
}

export async function generate() {
  const [sources, styleMaps] = await Promise.all([
    readSources(),
    getStyleMaps({ withShadcn: true }),
  ]);
  const markers = new Set(sources.flatMap((source) => [...getMarkers(source)]));

  const css = STYLES.map(({ name }) => {
    const styleMap = styleMaps.get(name)!;
    const rules = Object.entries(styleMap)
      .filter(([marker]) => markers.has(marker))
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([marker, classes]) => `  .${marker} {\n    @apply ${classes};\n  }`,
      );
    return `.style-${name} {\n${rules.join("\n\n")}\n}\n`;
  });

  const icons = [
    ...new Set(
      sources.flatMap((source) =>
        [...source.matchAll(/\blucide="(\w+)"/g)].map(([, icon]) => icon),
      ),
    ),
  ].sort();

  await Promise.all([
    writeFileIfChanged(
      path.join(GENERATED_PATH, "styles.css"),
      `/* ${HEADER} */\n\n${css.join("\n")}`,
    ),
    writeFileIfChanged(
      path.join(GENERATED_PATH, "icons.ts"),
      `// ${HEADER}\n\nexport {\n${icons.map((icon) => `  ${icon},`).join("\n")}\n} from "lucide-react";\n`,
    ),
    writeFileIfChanged(
      path.join(GENERATED_PATH, "registries.ts"),
      await getRegistriesModule(),
    ),
  ]);
}

export function watchRegistry() {
  let timer: ReturnType<typeof setTimeout> | undefined;
  watch(REGISTRY_PATH, { recursive: true }, (_event, file) => {
    if (
      !file ||
      file.startsWith("__generated__") ||
      !/\.(css|json|tsx?)$/.test(file)
    )
      return;
    clearTimeout(timer);
    timer = setTimeout(
      () => generate().catch((error: unknown) => console.error(error)),
      50,
    );
  });
}

if (import.meta.main) {
  await generate();
  if (process.argv.includes("--watch")) watchRegistry();
}
